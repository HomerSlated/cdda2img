def _fold(name: str) -> str:
    """Case, ``&``/``and`` and a leading or trailing "the" folded away."""
    s = " ".join(name.replace("&", " and ").split()).casefold()
    s = s.removeprefix("the ").removesuffix(", the")
    return s


_FOLDED: dict[str, str] = {_fold(k): v for k, v in _DISCOGS.items()}


def discogs_country_code(name: object) -> str | None:
    """The code for a Discogs country *name*, or ``None`` when no code fits.

    ``None`` for a region no code describes, for "Unknown", and for a name the
    table does not know (logged, so a gap in the table can be found).
    """
    if not isinstance(name, str) or not name.strip():
        return None
    code = _FOLDED.get(_fold(name))
    if code is None:
        log.info("Discogs country %r has no code; left blank", name)
    return code
